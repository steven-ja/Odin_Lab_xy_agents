    a.metric('Accessible households', len(results))
    b.metric('Reported total assets', f'{total:,.0f} SEK')
    c.metric('Active findings', len(all_findings))
    d.metric('Critical flags', sum(f['severity'] == 'critical' for f in all_findings))


