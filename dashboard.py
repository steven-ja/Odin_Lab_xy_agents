"""Streamlit UI for the governed Synthetic XY / LangGraph prototype.

Run from the repository root: streamlit run dashboard.py
Advisor switching is for an OFFLINE DEMO only, not authentication.
"""
from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

import pandas as pd
import streamlit as st

from xy_agents.case import CaseAnalyzer, CaseRepository, INJECTION
from xy_agents.graph import build_graph, run_graph
from xy_agents.security import AccessGateway, Forbidden, InMemoryAudit

ROOT = Path(__file__).resolve().parent
DATA = ROOT / 'fixtures'
SEVERITY = ['critical', 'high', 'warning', 'info']

st.set_page_config(page_title='XY | Governed Advisory Intelligence', page_icon='🛡️',
                   layout='wide', initial_sidebar_state='expanded')


@st.cache_resource(show_spinner='Validating synthetic case data…')
def repository(data_path: str) -> CaseRepository:
    return CaseRepository(Path(data_path))


def safe_display(text: str, household: dict[str, str]) -> str:
    """Mask known identifiers plus obvious email/phone patterns for display."""
    for key in ('personnummer', 'namn', 'epost', 'telefon'):
        value = household.get(key, '')
        if value:
            text = text.replace(value, '[REDACTED]')
    text = re.sub(r'[\w.\-+]+@[\w.\-]+\.[A-Za-z]{2,}', '[EMAIL REDACTED]', text)
    text = re.sub(r'\b\d{8}[-+]\d{4}\b', '[PERSONAL ID REDACTED]', text)
    return text


def render_findings(findings: list[dict], key: str) -> None:
    if not findings:
        st.success('No findings generated by current rules; this is not a clean bill of health.')
        return
    df = pd.DataFrame([{
        'Severity': f['severity'], 'Code': f['code'], 'Detail': f['detail'],
        'Evidence': ', '.join(f['evidence']),
    } for f in findings])
    choices = st.multiselect('Filter severity', SEVERITY, default=SEVERITY, key=key)
    filtered = df[df['Severity'].isin(choices)]
    st.dataframe(filtered, width='stretch', hide_index=True)


def graph_dot(compiled, visited: set[str]) -> str:
    """Render compiled LangGraph topology, not a manually copied flowchart."""
    internal = compiled.get_graph()
    lines = ['digraph Workflow {', 'rankdir=LR;',
             'graph [pad="0.3", nodesep="0.3", ranksep="0.5", bgcolor="transparent"];',
             'node [shape="box", style="rounded,filled", color="#B5C5D8", '
             'fontname="Helvetica", fontsize="10", margin="0.15,0.12"];',
             'edge [color="#7B90A5", arrowsize="0.65"];']
    for node_id in internal.nodes:
        node_id = str(node_id)
        fill = '#D2F2E0' if node_id in visited else '#EBF1F8'
        if node_id.startswith('__'):
            fill = '#E6E6EB'
        lines.append(f'{json.dumps(node_id)} [label={json.dumps(node_id.replace("_", " "))}, fillcolor="{fill}"];')
    for edge in internal.edges:
        lines.append(f'{json.dumps(str(edge.source))} -> {json.dumps(str(edge.target))};')
    return '\n'.join([*lines, '}'])


def header_metrics(results: list[dict]) -> None:
    all_findings = [f for r in results for f in r['findings']]
    total = sum(int(r['assets']['total_sek']) for r in results)
    a, b, c, d = st.columns(4)
    a.metric('Accessible households', len(results))
    b.metric('Reported total assets', f'{total:,.0f} SEK')
    c.metric('Active findings', len(all_findings))
    d.metric('Critical flags', sum(f['severity'] == 'critical' for f in all_findings))


st.title('XY · Governed Advisory Intelligence')
st.caption('Synthetic data · 29 Sep 2026 · Read-only · Deterministic analytics orchestrated with LangGraph')
st.warning('**Offline demonstration:** selecting an advisor ID is NOT authentication. Do not deploy '
           'with real client data without SSO, server-side row-level access controls and persistent audit logging.',
           icon='⚠️')

repo = repository(str(DATA))
if 'audit' not in st.session_state:
    st.session_state.audit = InMemoryAudit()
audit = st.session_state.audit
gateway = AccessGateway(audit)
analyzer = CaseAnalyzer(repo, gateway)

with st.sidebar:
    st.header('Session scope')
    advisor_id = st.selectbox('Demo advisor identity', sorted(repo.advisors.keys()),
                              help='Simulation only: production identity must come from verified authentication.')
    principal = repo.principal(advisor_id)
    allowed = sorted(principal.allowed_households)
    household_id = st.selectbox('Authorized household', allowed)
    st.caption(f'Visible households: {len(allowed)} of {len(repo.households)}')
    st.divider()
    st.caption(f'Data SHA-256: {repo.fingerprint()[:16]}…')
    st.caption('No model/API calls; no CRM writes.')
    st.caption('See the LangGraph tab for the compiled workflow and execution trace.')

# Switching principals or cases must not expose previous conversations.
scope = f'{advisor_id}:{household_id}'
if st.session_state.get('last_scope') != scope:
    st.session_state.last_scope = scope
    st.session_state.history = []
    st.session_state.last_trace = ()
    st.session_state.last_checks = ()

# All reads shown below pass through the permission gateway first.
try:
    household, holding_rows, meetings, transcripts = repo.scoped(principal, household_id, gateway)
    case = analyzer.analyze(principal, household_id)
except Forbidden:
    st.error('Access denied. No household data was loaded.')
    st.stop()

# Aggregate view uses the same authorized per-household analysis pathway.
results = [analyzer.analyze(principal, hid) for hid in allowed]
header_metrics(results)

tab_overview, tab_household, tab_agent, tab_graph, tab_audit = st.tabs(
    ['Overview', 'Household & sources', 'Ask the agents', 'LangGraph execution', 'Audit & governance'])

with tab_overview:
    st.subheader('Portfolio and monitoring overview · permission-scoped')
    rows = [{
        'Household': r['household_id'], 'Assets (SEK)': float(r['assets']['total_sek']),
        'Holdings (SEK)': float(r['holdings']['valuation_sek']),
        'Findings': len(r['findings']), 'Critical': sum(f['severity'] == 'critical' for f in r['findings']),
        'Risk': r['recorded_risk_profile'] or 'missing',
    } for r in results]
    overview = pd.DataFrame(rows)
    st.dataframe(overview, width='stretch', hide_index=True)
    left, right = st.columns(2)
    with left:
        st.markdown('**Reported assets by household**')
        st.bar_chart(overview.set_index('Household')['Assets (SEK)'])
    with right:
        st.markdown('**Finding severity distribution**')
        counts = Counter(f['severity'] for r in results for f in r['findings'])
        st.bar_chart(pd.DataFrame({'Count': [counts.get(s, 0) for s in SEVERITY]}, index=SEVERITY))
    st.caption('Values are descriptive for authorized households only. No inferences about a population.')

with tab_household:
    st.subheader(f'Household {household_id}')
    assets = case['assets']; holdings = case['holdings']
    a, b, c = st.columns(3)
    a.metric('Cash', f"{float(assets['cash_sek']):,.0f} SEK")
    b.metric('ISK', f"{float(assets['isk_sek']):,.0f} SEK")
    c.metric('KF', f"{float(assets['kf_sek']):,.0f} SEK")
    st.caption(f"Risk profile: {case['recorded_risk_profile'] or 'missing'} · "
               f"Suitability complete: {case['suitability_complete']} · "
               f"Holding-row HHI: {holdings['holding_row_hhi'] or 'undefined'}")
    if not holdings['full_fee_coverage']:
        st.warning('Annual fee coverage is incomplete. Weighted fee excludes unknown-fee holdings.')
    ftab, htab, stab = st.tabs(['Findings', 'Holdings', 'Source documents'])
    with ftab:
        render_findings(case['findings'], key='household_severity')
    with htab:
        # Never display the raw household CRM record, name, phone, email or personal ID.
        safe_cols = ['kontotyp', 'isin', 'instrument', 'varde_sek', 'arlig_avgift_pct', 'per_datum']
        df = pd.DataFrame(holding_rows, columns=safe_cols)
        st.dataframe(df, width='stretch', hide_index=True)
        st.download_button('Download authorized holdings CSV', df.to_csv(index=False).encode('utf-8'),
                           file_name=f'{household_id}_holdings.csv', mime='text/csv')
    with stab:
        st.info('CRM notes and transcripts are **untrusted source material**. Displaying them '
                'does not execute their instructions. The LangGraph state never contains raw notes.')
        reveal = st.checkbox('Display source excerpts (PII redacted)', value=False)
        st.write(f'{len(meetings)} meeting notes · {len(transcripts)} transcript files')
        if reveal:
            for meeting in meetings:
                unsafe = bool(INJECTION.search(meeting['anteckning']))
                with st.expander(f"Meeting {meeting['mote_id']} · {meeting['datum']}" +
                                 (' · QUARANTINED' if unsafe else '')):
                    st.code(safe_display(meeting['anteckning'], household), language='text')
            for filename, text in transcripts:
                unsafe = bool(INJECTION.search(text))
                with st.expander(filename + (' · INJECTION INDICATOR' if unsafe else '')):
                    st.code(safe_display(text, household), language='text')

with tab_agent:
    st.subheader('Ask the governed LangGraph agents')
    st.caption('Examples: “Explain fees and missing data”, “What is the risk-profile conflict?”, '
               '“Show transcript evidence”, “Summarize this portfolio”. '
               'Answers come from deterministic tools and evidence; this is not a generative LLM.')
    for message in st.session_state.history:
        with st.chat_message(message['role']):
            st.markdown(message['content'])
    question = st.chat_input('Ask a question about this authorized household…', key='agent_input')
    if question and question.strip():
        st.session_state.history.append({'role': 'user', 'content': question})
        with st.chat_message('user'):
            st.write(question)
        with st.chat_message('assistant'):
            try:
                graph = build_graph(repo, audit)
                with st.spinner('Executing LangGraph nodes…'):
                    run = run_graph(graph, advisor_id, household_id, question)
                st.markdown(run.answer)
                st.session_state.history.append({'role': 'assistant', 'content': run.answer})
                st.session_state.last_trace = run.trace
                st.session_state.last_checks = run.checks
                st.caption('Execution: ' + ' → '.join(run.trace))
            except Forbidden:
                st.error('Access denied; no answer generated.')
            except Exception as exc:
                st.error(f'Graph execution failed ({type(exc).__name__}). Check dependency installation.')

with tab_graph:
    st.subheader('Actual LangGraph topology')
    st.caption('Generated from the compiled graph via get_graph(); green nodes ran in the last chat request.')
    try:
        compiled = build_graph(repo, audit)
        st.graphviz_chart(graph_dot(compiled, set(st.session_state.last_trace)),
                          width='stretch')
        with st.expander('LangGraph Mermaid source'):
            st.code(compiled.get_graph().draw_mermaid(), language='mermaid')
        st.subheader('Last execution')
        if st.session_state.last_trace:
            trace = pd.DataFrame([{'Step': i + 1, 'Node': node} for i, node in enumerate(st.session_state.last_trace)])
            st.dataframe(trace, hide_index=True, width='stretch')
            st.success('Independent numeric verifier passed.')
            for check in st.session_state.last_checks:
                st.write('✓ ' + check)
        else:
            st.info('Run a chat query to inspect the executed nodes and verifier checks.')
    except RuntimeError as exc:
        st.error(str(exc))

with tab_audit:
    st.subheader('Authorization and governance')
    st.write('All report reads are checked against advisor permissions. The audit log below '
             'is **in-memory and session-local**: it is not production-grade durable logging.')
    events = pd.DataFrame(audit.events, columns=['Advisor', 'Household', 'Operation', 'Allowed'])
    st.dataframe(events.tail(150), hide_index=True, width='stretch')
    st.caption('Production requirements: verified login/SSO, DB row-level security, immutable audit trail, '
               'DLP/PII review, retention policy, vendor diligence and human-approved writes.')
